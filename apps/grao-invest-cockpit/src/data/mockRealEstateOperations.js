    expected_result_pct: expectedPct,
    moment_result_pct: 0,
    entry_price_brl: entry,
    current_price_brl: current,
    target_price_brl: target,
    stop_price_brl: stop,
    source_url: sourceUrl,
    operation_plan: plan,
    structured_operation: structure,
    exit_rule: exitRule,
